def team_abbr(name: str | None) -> str:
    if not name:
        return ""
    return TEAM_ABBR.get(name.strip(), name.strip()[:3].upper())


def team_nickname(name: str | None) -> str:
    """'Chicago Bears' -> 'Bears'."""
    if not name:
        return ""
    return name.strip().split(" ")[-1]
